/**
 * Lightweight editor i18n.
 *
 * The editor ships two languages: Simplified Chinese (`zh`) and English (`en`).
 * Language detection follows the browser's ordered locale list; only Simplified
 * Chinese tags map to `zh`. Everything else falls back to English.
 */

export const DEFAULT_LANGUAGE = 'en';
export const SUPPORTED_LANGUAGES = ['zh', 'en'];
export const LANGUAGE_STORAGE_KEY = 'albedo-svg-studio:lang:v1';

const SIMPLIFIED_CHINESE = new Set(['zh', 'zh-hans', 'zh-cn', 'zh-sg']);

export function normalizeLanguage(value) {
  return value === 'zh' ? 'zh' : value === 'en' ? 'en' : null;
}

function languageFromTag(tag) {
  const normalized = String(tag || '').trim().toLowerCase().replace(/_/g, '-');
  if (!normalized) return null;
  if (SIMPLIFIED_CHINESE.has(normalized)) return 'zh';
  if (normalized.startsWith('zh-hans-') || normalized.startsWith('zh-cn-') || normalized.startsWith('zh-sg-')) return 'zh';
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
  return null;
}

/**
 * Pick the first supported locale from a `navigator.languages`-style list.
 * Traditional Chinese tags deliberately do not match Simplified Chinese and
 * therefore fall through to English.
 */
export function detectLanguage(languages) {
  const list = Array.isArray(languages) ? languages : [languages];
  for (const tag of list) {
    const language = languageFromTag(tag);
    if (language) return language;
  }
  return DEFAULT_LANGUAGE;
}

function interpolate(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  ));
}

