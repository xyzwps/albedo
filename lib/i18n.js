export const MESSAGES = { zh: ZH, en: EN };

export function translate(language, key, vars = {}) {
  const lang = normalizeLanguage(language) || languageFromTag(language) || DEFAULT_LANGUAGE;
  const dictionary = MESSAGES[lang];
  const fallback = MESSAGES[DEFAULT_LANGUAGE];
  const template = dictionary[key] ?? fallback[key] ?? key;
  return interpolate(template, vars);
}

export function translateCount(language, key, count, vars = {}) {
  const suffix = count === 1 ? '.one' : '.other';
  const lang = normalizeLanguage(language) || languageFromTag(language) || DEFAULT_LANGUAGE;
  const dictionary = MESSAGES[lang];
  const fallback = MESSAGES[DEFAULT_LANGUAGE];
  const template = dictionary[key + suffix] ?? dictionary[key] ??
    fallback[key + suffix] ?? fallback[key] ?? key;
  return interpolate(template, { ...vars, count });
}
